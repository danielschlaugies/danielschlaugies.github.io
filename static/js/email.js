document.addEventListener("DOMContentLoaded", () => {
    const el = document.querySelectorAll(".legal-email");
    if (!el) {
        return;
    } 

    const encoded = [
         0x63 , 0x6f , 0x6e , 0x74 , 0x61 , 0x63 , 0x74 , 0x40 , 0x64 , 0x61 , 0x6e , 0x69 , 0x65 , 0x6c , 0x73 , 0x63 , 0x68 , 0x6c , 0x61 , 0x75 , 0x67 , 0x69 , 0x65 , 0x73 , 0x2e , 0x63 , 0x6f , 0x6d ,
    ]

    el.forEach((e) => {
        e.innerText = String.fromCharCode(...encoded)
    });
});